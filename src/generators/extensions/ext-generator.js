import { join } from 'node:path';
import { writeText, ensureDir } from '../../utils/fs.js';
import * as log from '../../utils/logger.js';

/**
 * Generate extension configuration stubs.
 * (Full extension installation is Phase 2 — this creates placeholder configs)
 */
export async function generateExtensions(projectRoot, roles, userConfig) {
  if (userConfig.interactionMode === 'direct') {
    log.info('Skipping extensions (direct mode)');
    return [];
  }

  log.info('Generating extension configs...');
  const generated = [];

  // Head agent config
  const extDir = join(projectRoot, '.pi', 'extensions');
  await ensureDir(extDir);

  const buildTeams = roles.filter((r) => r.category === 'build-team');

  // Generate head-agent config
  const headAgentConfig = {
    teams: buildTeams.map((r) => r.name),
    interactionMode: userConfig.interactionMode,
    features: {
      contextBus: userConfig.features.contextBus,
      mail: true,
      cron: true,
    },
    orgIntro: 'You are the orchestrator. Your ONLY job is to delegate work to specialized teams.',
  };

  await writeText(
    join(extDir, 'head-agent-config.json'),
    JSON.stringify(headAgentConfig, null, 2) + '\n'
  );
  generated.push('.pi/extensions/head-agent-config.json');
  log.bullet('head-agent config → .pi/extensions/head-agent-config.json');

  // Generate constants.ts stub
  const constantsContent = `// Auto-generated by pi-org-bootstrap
// DO NOT EDIT — regenerate with: npx pi-org-bootstrap regenerate extensions

export const TEAMS = [
${buildTeams.map((r) => `  "${r.name}",`).join('\n')}
] as const;

export const TEAM_ORDER = [...TEAMS];

export const ALL_AGENTS = [
  "dispatcher",
  "tech-lead",
  "reviewer",
${roles.some((r) => r.name === 'security-officer') ? '  "security-officer",\n' : ''}${buildTeams.map((r) => `  "${r.name}",`).join('\n')}
  "pi-extensions",
  "pi-agents",
  "pi-skills",
  "pi-config",
] as const;
`;

  await writeText(join(extDir, 'constants.ts'), constantsContent);
  generated.push('.pi/extensions/constants.ts');
  log.bullet('constants → .pi/extensions/constants.ts');

  return generated;
}
